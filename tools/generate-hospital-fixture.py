#!/usr/bin/env python3
"""Generates the hospital fixture databases.

Two databases are produced from the same schema:

  hospital.sql          the one every SQL lesson works against
  hospital-variant.sql  the same schema with different rows

The variant exists for one reason: it is what stops a learner passing a query
exercise by typing the expected rows as literals. Every `sql-result` grader
runs the learner's query and the reference query against BOTH databases and
requires both to agree, so an answer that does not actually query cannot pass.

Run with: python3 tools/generate-hospital-fixture.py
Deterministic — the same seed always produces the same file, so regenerating
never creates a spurious diff.
"""

import random
from pathlib import Path

SCHEMA = """-- Conductor — hospital fixture
-- Generated by tools/generate-hospital-fixture.py. Do not edit by hand.

PRAGMA foreign_keys = ON;

CREATE TABLE departments (
    id        INTEGER PRIMARY KEY,
    name      TEXT    NOT NULL UNIQUE,
    floor     INTEGER NOT NULL,
    phone     TEXT    NOT NULL
);

CREATE TABLE doctors (
    id            INTEGER PRIMARY KEY,
    full_name     TEXT    NOT NULL,
    specialty     TEXT    NOT NULL,
    department_id INTEGER NOT NULL REFERENCES departments(id),
    hired_on      TEXT    NOT NULL
);

CREATE TABLE patients (
    id             INTEGER PRIMARY KEY,
    full_name      TEXT    NOT NULL,
    date_of_birth  TEXT    NOT NULL,
    blood_type     TEXT,
    admitted_on    TEXT    NOT NULL,
    discharged_on  TEXT,
    department_id  INTEGER REFERENCES departments(id)
);

CREATE TABLE appointments (
    id            INTEGER PRIMARY KEY,
    patient_id    INTEGER NOT NULL REFERENCES patients(id),
    doctor_id     INTEGER NOT NULL REFERENCES doctors(id),
    scheduled_for TEXT    NOT NULL,
    status        TEXT    NOT NULL CHECK (status IN ('booked', 'attended', 'missed', 'cancelled')),
    reason        TEXT
);

CREATE TABLE prescriptions (
    id          INTEGER PRIMARY KEY,
    patient_id  INTEGER NOT NULL REFERENCES patients(id),
    doctor_id   INTEGER NOT NULL REFERENCES doctors(id),
    drug        TEXT    NOT NULL,
    dose_mg     INTEGER NOT NULL,
    started_on  TEXT    NOT NULL,
    ended_on    TEXT
);

CREATE INDEX idx_appointments_patient ON appointments(patient_id);
CREATE INDEX idx_prescriptions_patient ON prescriptions(patient_id);
"""

DEPARTMENTS = [
    ("Emergency", 1, "555-0101"),
    ("Cardiology", 3, "555-0102"),
    ("Paediatrics", 2, "555-0103"),
    ("Orthopaedics", 4, "555-0104"),
    ("Oncology", 5, "555-0105"),
    ("Radiology", 1, "555-0106"),
]

SPECIALTIES = {
    "Emergency": ["Emergency medicine", "Trauma surgery"],
    "Cardiology": ["Cardiology", "Electrophysiology"],
    "Paediatrics": ["Paediatrics", "Neonatology"],
    "Orthopaedics": ["Orthopaedic surgery", "Sports medicine"],
    "Oncology": ["Medical oncology", "Haematology"],
    "Radiology": ["Diagnostic radiology", "Interventional radiology"],
}

FIRST = [
    "Asha", "Bikash", "Chandra", "Deepa", "Elina", "Farhan", "Gita", "Hari",
    "Indira", "Jyoti", "Kiran", "Laxmi", "Manish", "Nabin", "Ojaswi", "Prakash",
    "Rajan", "Sabina", "Tenzin", "Usha", "Vikram", "Yamuna", "Anita", "Bimal",
    "Clara", "Dinesh", "Esha", "Gopal", "Hema", "Ishan",
]
LAST = [
    "Shrestha", "Gurung", "Tamang", "Rai", "Magar", "Thapa", "Adhikari",
    "Bhattarai", "Karki", "Lama", "Maharjan", "Pradhan", "Sherpa", "Limbu",
]
BLOOD = ["O+", "A+", "B+", "AB+", "O-", "A-", "B-", None]
DRUGS = [
    ("Amoxicillin", [250, 500]),
    ("Paracetamol", [500, 1000]),
    ("Atorvastatin", [10, 20, 40]),
    ("Metformin", [500, 850]),
    ("Salbutamol", [100, 200]),
    ("Omeprazole", [20, 40]),
    ("Ibuprofen", [200, 400]),
]
REASONS = [
    "Chest pain", "Follow-up", "Fractured wrist", "Routine check",
    "Shortness of breath", "Persistent cough", "Post-surgery review",
    "Headache", "Abdominal pain", "Vaccination",
]
STATUSES = ["booked", "attended", "attended", "attended", "missed", "cancelled"]


def q(value):
    """SQL literal for a Python value."""
    if value is None:
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def date(rng, start_year, end_year):
    return f"{rng.randint(start_year, end_year)}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"


def build(seed, doctor_count, patient_count, path):
    rng = random.Random(seed)
    lines = [SCHEMA, ""]

    lines.append("INSERT INTO departments (id, name, floor, phone) VALUES")
    rows = [f"    ({i + 1}, {q(n)}, {q(f)}, {q(p)})" for i, (n, f, p) in enumerate(DEPARTMENTS)]
    lines.append(",\n".join(rows) + ";\n")

    lines.append("INSERT INTO doctors (id, full_name, specialty, department_id, hired_on) VALUES")
    rows = []
    for i in range(doctor_count):
        dept_index = rng.randrange(len(DEPARTMENTS))
        dept_name = DEPARTMENTS[dept_index][0]
        name = f"Dr {rng.choice(FIRST)} {rng.choice(LAST)}"
        specialty = rng.choice(SPECIALTIES[dept_name])
        rows.append(
            f"    ({i + 1}, {q(name)}, {q(specialty)}, {dept_index + 1}, {q(date(rng, 2009, 2024))})"
        )
    lines.append(",\n".join(rows) + ";\n")

    lines.append(
        "INSERT INTO patients (id, full_name, date_of_birth, blood_type, admitted_on, discharged_on, department_id) VALUES"
    )
    rows = []
    for i in range(patient_count):
        name = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        admitted = date(rng, 2026, 2026)
        # About a third are still in the hospital: NULL discharged_on is what
        # makes "who is still here?" a real question rather than a toy one.
        discharged = None if rng.random() < 0.34 else date(rng, 2026, 2026)
        rows.append(
            f"    ({i + 1}, {q(name)}, {q(date(rng, 1940, 2024))}, {q(rng.choice(BLOOD))}, "
            f"{q(admitted)}, {q(discharged)}, {rng.randint(1, len(DEPARTMENTS))})"
        )
    lines.append(",\n".join(rows) + ";\n")

    lines.append(
        "INSERT INTO appointments (id, patient_id, doctor_id, scheduled_for, status, reason) VALUES"
    )
    rows = []
    appointment_id = 1
    for patient_id in range(1, patient_count + 1):
        for _ in range(rng.randint(0, 3)):
            rows.append(
                f"    ({appointment_id}, {patient_id}, {rng.randint(1, doctor_count)}, "
                f"{q(date(rng, 2026, 2026))}, {q(rng.choice(STATUSES))}, {q(rng.choice(REASONS))})"
            )
            appointment_id += 1
    lines.append(",\n".join(rows) + ";\n")

    lines.append(
        "INSERT INTO prescriptions (id, patient_id, doctor_id, drug, dose_mg, started_on, ended_on) VALUES"
    )
    rows = []
    prescription_id = 1
    for patient_id in range(1, patient_count + 1):
        for _ in range(rng.randint(0, 2)):
            drug, doses = rng.choice(DRUGS)
            started = date(rng, 2026, 2026)
            ended = None if rng.random() < 0.4 else date(rng, 2026, 2026)
            rows.append(
                f"    ({prescription_id}, {patient_id}, {rng.randint(1, doctor_count)}, "
                f"{q(drug)}, {rng.choice(doses)}, {q(started)}, {q(ended)})"
            )
            prescription_id += 1
    lines.append(",\n".join(rows) + ";\n")

    Path(path).write_text("\n".join(lines))
    print(f"{path}: {doctor_count} doctors, {patient_count} patients, "
          f"{appointment_id - 1} appointments, {prescription_id - 1} prescriptions")


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent / "content" / "fixtures"
    root.mkdir(parents=True, exist_ok=True)
    build(20261118, 14, 60, root / "hospital.sql")
    # Different seed and different sizes: a learner who hardcodes the primary
    # database's answers gets a different result set here, and fails.
    build(777, 9, 41, root / "hospital-variant.sql")
